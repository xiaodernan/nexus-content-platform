import { readFileSync, writeFileSync } from 'node:fs';
const PLAN = 'D:/终极项目/docs/LONG_TERM_PLAN.md';
const ITEM = 'D:/终极项目/.nexus-tmp/item169.txt';
let text = readFileSync(ITEM, 'utf8');
if (text.includes('\r')) throw new Error('item has CR');
if (text.includes('﻿')) throw new Error('item has BOM');
if (text.includes('\uFFFD')) throw new Error('item has U+FFFD');
const asciiQuotes = (text.match(/"/g) || []).length;
const plan = readFileSync(PLAN, 'utf8');
if (plan.includes('\r')) throw new Error('plan has CR');
if (plan.includes('169. ~~**v568')) { console.log('item 169 already present'); process.exit(0); }
const lines = plan.split('\n');
const at = lines.findIndex((l) => l.startsWith('168.'));
if (at < 0) throw new Error('no line starts with 168.');
if (!lines[at + 1].startsWith('31.')) throw new Error(`line after 168 is not the legacy 31.: ${JSON.stringify(lines[at + 1].slice(0, 40))}`);
const before = lines.length;
lines.splice(at + 1, 0, text.replace(/\n$/, ''));
writeFileSync(PLAN, lines.join('\n'), 'utf8');
const after = readFileSync(PLAN, 'utf8');
const out = after.split('\n');
const item = out.find((l) => l.startsWith('169.')) || '';
console.log(`lines ${before} -> ${out.length} · CR ${after.split('\r').length - 1} · U+FFFD ${(after.match(/\uFFFD/g) || []).length} · ascii double-quotes in item: ${asciiQuotes}`);
console.log(`item chars: ${item.length} · 169 present: ${item.startsWith('169.')} · next line still legacy: ${out[at + 2].slice(0, 6)}`);
console.log(`head: ${item.slice(0, 70)}`);
console.log(`tail: ${item.slice(-70)}`);
