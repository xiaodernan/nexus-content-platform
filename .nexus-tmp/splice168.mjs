import { readFileSync, writeFileSync } from 'node:fs';
const PLAN = 'D:/\u7ec8\u6781\u9879\u76ee/docs/LONG_TERM_PLAN.md';
const ITEM = 'D:/\u7ec8\u6781\u9879\u76ee/.nexus-tmp/item168.txt';
let text = readFileSync(ITEM, 'utf8');
text = text.replace(/"\u62c6\u9669"/g, '\u201c\u62c6\u9669\u201d');
if (text.includes('\r')) throw new Error('item has CR');
if (text.includes('\uFFFD')) throw new Error('item has U+FFFD');
const plan = readFileSync(PLAN, 'utf8');
if (plan.includes('\r')) throw new Error('plan has CR');
const lines = plan.split('\n');
const at = lines.findIndex((l) => l.startsWith('167.'));
if (at < 0) throw new Error('no line starts with 167.');
if (!lines[at + 1].startsWith('31.')) throw new Error(`line after 167 is not the legacy 31.: ${JSON.stringify(lines[at + 1].slice(0, 40))}`);
const before = lines.length;
lines.splice(at + 1, 0, text.replace(/\n$/, ''));
writeFileSync(PLAN, lines.join('\n'), 'utf8');
const after = readFileSync(PLAN, 'utf8');
const outLines = after.split('\n');
console.log(`lines ${before} -> ${outLines.length} · CR ${after.split('\r').length - 1} · U+FFFD ${(after.match(/\uFFFD/g) || []).length}`);
console.log(`168 present: ${outLines.some((l) => l.startsWith('168.'))} · item chars: ${text.trim().length}`);
console.log(`quote check: ${(outLines.find((l) => l.startsWith('168.')) || '').includes('\u201c\u62c6\u9669\u201d')}`);
