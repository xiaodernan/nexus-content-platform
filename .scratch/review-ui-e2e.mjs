import { chromium } from 'playwright';
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errs = [];
page.on('pageerror', (e) => errs.push(String(e).slice(0, 100)));
await page.goto('http://127.0.0.1:3100/', { waitUntil: 'networkidle', timeout: 60000 });
await page.waitForSelector('[data-project-name-input]', { timeout: 30000 });
await page.fill('[data-project-name-input]', '自查开关实测');
await page.waitForSelector('[data-create-project]:not([disabled])', { timeout: 10000 });
const resp = page.waitForResponse((r) => new URL(r.url()).pathname === '/api/projects', { timeout: 15000 }).catch(() => null);
await page.click('[data-create-project]');
await resp;
await page.waitForURL(/\/studio\/[^/]+$/, { timeout: 60000 });
await page.waitForSelector('[data-canvas-frame]', { timeout: 60000 });
const review = page.locator('[data-ai-review]');
console.log('review checkbox count', await review.count());
await review.check();
console.log('checked', await review.isChecked());
const posts = [];
page.on('request', (r) => { if (r.url().includes('/api/ai/run')) posts.push(r.postData() || ''); });
await page.fill('[data-ai-input]', '把主标题改成 72px，并加一句副标题');
await page.locator('[data-ai-submit]').click().catch(async () => {
  await page.getByRole('button', { name: '执行' }).first().click();
});
await page.waitForTimeout(15000);
const bodyText = (await page.locator('body').innerText()).replace(/\s+/g, ' ');
const reviewInBody = /自查|review|审稿/.test(bodyText);
console.log(JSON.stringify({ posts: posts.map(p => { try { const j = JSON.parse(p); return { review: j.review, intent: j.intent }; } catch { return p.slice(0, 80); } }), reviewInBody, tail: bodyText.slice(-600), errs: errs.slice(0, 3) }, null, 1));
await page.screenshot({ path: '.scratch/review-ui.png', fullPage: false });
await browser.close();
