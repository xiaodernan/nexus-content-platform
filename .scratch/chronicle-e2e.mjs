import { chromium } from 'playwright';
const browser = await chromium.launch({ headless: true });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const page = await ctx.newPage();
const errs = [];
page.on('pageerror', (e) => errs.push(String(e).slice(0, 100)));
await page.goto('http://127.0.0.1:3100/', { waitUntil: 'networkidle', timeout: 60000 });
await page.waitForSelector('[data-project-name-input]', { timeout: 30000 });
await page.fill('[data-project-name-input]', '编年续写实测');
await page.waitForSelector('[data-create-project]:not([disabled])', { timeout: 10000 });
const resp = page.waitForResponse((r) => new URL(r.url()).pathname === '/api/projects', { timeout: 15000 }).catch(() => null);
await page.click('[data-create-project]');
await resp;
await page.waitForURL(/\/studio\/[^/]+$/, { timeout: 60000 });
const id = new URL(page.url()).pathname.split('/').pop();
await page.waitForSelector('[data-canvas-frame]', { timeout: 60000 });
await page.click('[data-panel-tab="world"]');
await page.waitForSelector('[data-world-panel]', { timeout: 30000 });
const create = page.locator('[data-world-create]');
if (await create.count()) await create.click();
await page.waitForSelector('[data-world-ai-chronicle]', { timeout: 30000 });
await page.fill('[data-world-summary]', '潮候院用一口老石磨记时；每逢潮退，磨盘会磨出不属于这个纪元的盐。');
await page.locator('[data-world-summary]').press('Tab');
await page.waitForTimeout(1500);
const before = (await ctx.request.get(`http://127.0.0.1:3100/api/projects/${id}/world`)).json();
const b = await before;
const beforeStory = (b.world?.nodes || []).filter((n) => n.kind === 'story').length;
await page.click('[data-world-ai-chronicle]');
await page.waitForSelector('[data-world-ai-chronicle-note]', { timeout: 120000 });
const note = await page.locator('[data-world-ai-chronicle-note]').textContent();
await page.waitForTimeout(3000);
const afterDoc = await (await ctx.request.get(`http://127.0.0.1:3100/api/projects/${id}/world`)).json();
const stories = (afterDoc.world?.nodes || []).filter((n) => n.kind === 'story');
console.log(JSON.stringify({ note, beforeStory, afterStory: stories.length, added: stories.filter((n) => (n.body || '').length > 20).map((n) => ({ title: n.title, body: n.body.slice(0, 90), lore: n.lore })), errs: errs.slice(0, 3) }, null, 1));
await page.screenshot({ path: '.scratch/chronicle-e2e.png', fullPage: false });
await browser.close();
