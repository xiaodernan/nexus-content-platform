import { chromium } from 'playwright';
const browser = await chromium.launch({ headless: true });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const page = await ctx.newPage();
const errs = [];
page.on('pageerror', (e) => errs.push(String(e).slice(0, 100)));
await page.goto('http://127.0.0.1:3100/', { waitUntil: 'networkidle', timeout: 60000 });
await page.waitForSelector('[data-project-name-input]', { timeout: 30000 });
await page.fill('[data-project-name-input]', '记忆回声实测');
await page.waitForSelector('[data-create-project]:not([disabled])', { timeout: 10000 });
const resp = page.waitForResponse((r) => new URL(r.url()).pathname === '/api/projects', { timeout: 15000 }).catch(() => null);
await page.click('[data-create-project]');
await resp;
await page.waitForURL(/\/studio\/[^/]+$/, { timeout: 60000 });
const id = new URL(page.url()).pathname.split('/').pop();
await page.waitForSelector('[data-canvas-frame]', { timeout: 60000 });
await page.click('[data-panel-tab="world"]');
await page.waitForSelector('[data-world-panel]', { timeout: 30000 });
const create = page.locator('[data-world-create]');
if (await create.count()) await create.click();
await page.waitForSelector('[data-world-ai-fill]', { timeout: 30000 });
await page.fill('[data-world-summary]', '灰灯纪的潮候院用老石磨记时，潮退时磨出异纪盐。');
await page.locator('[data-world-summary]').press('Tab');
await page.waitForTimeout(1200);
// fill one geography node first so the echo has real text to draw from
await page.selectOption('[data-world-new-kind]', 'geography');
await page.click('[data-world-ai-fill]');
await page.waitForSelector('[data-world-ai-fill-note]', { timeout: 120000 });
const fillNote = await page.locator('[data-world-ai-fill-note]').textContent();
await page.waitForTimeout(2000);
const bodies = await page.locator('[data-world-body]').evaluateAll((els) => els.map((e) => ({ id: e.getAttribute('data-world-body'), v: e.value })));
const filled = bodies.find((b) => b.v && b.v.length > 30);
if (!filled) { console.log(JSON.stringify({ fillNote, filled: null })); await browser.close(); process.exit(0); }
await page.locator(`[data-world-ai-echo="${filled.id}"]`).click();
await page.waitForSelector('[data-world-ai-echo-note]', { timeout: 120000 });
const echoNote = await page.locator('[data-world-ai-echo-note]').textContent();
await page.waitForTimeout(2500);
const doc = await (await ctx.request.get(`http://127.0.0.1:3100/api/projects/${id}/world`)).json();
const node = (doc.world?.nodes || []).find((n) => n.id === filled.id);
console.log(JSON.stringify({ fillNote, echoNote, memory: node?.lore?.memory, keptEra: node?.lore?.era, keptOrder: node?.lore?.order, errs: errs.slice(0, 3) }, null, 1));
await page.screenshot({ path: '.scratch/echo-e2e.png', fullPage: false });
await browser.close();
